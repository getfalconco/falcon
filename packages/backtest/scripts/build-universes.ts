/**
 * Writes src/universe-lists.ts: the ticker lists behind Falcon's wide named
 * universes. Tickers and as-of dates only; no prices, volumes or weights are
 * committed (the inputs carry Yahoo- and SSGA-derived numbers and stay out of
 * the repository).
 *
 *   pnpm --filter @falcon/backtest exec node --import tsx scripts/build-universes.ts \
 *     --filers ../engine/.cache/graph-universe/universe-<date>.json \
 *     --spy-tickers <file with one SPY holding ticker per line> --spy-as-of YYYY-MM-DD
 *
 * Inputs:
 *   --filers       the graph's filer universe (packages/engine scripts/graph-universe.ts):
 *                  US-listed operating companies passing the liquidity gate, ranked by
 *                  20-day median dollar volume. Gives falcon_universe (all members) and
 *                  us_large_caps (the first 500 by that ranking).
 *   --spy-tickers  the Ticker column of SSGA's daily SPY holdings file
 *                  (ssga.com, holdings-daily-us-en-spy.xlsx), one per line. Gives sp500_today.
 *   packages/engine/data/graph.json (read in place) gives falcon_graph: every node with a plain US ticker.
 *
 * Refresh monthly, or whenever the filer universe or the graph is rebuilt.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

function arg(name: string): string | null {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? (process.argv[i + 1] ?? null) : null;
}

const PLAIN = /^[A-Z]{1,5}(-[A-Z])?$/;
/** Yahoo spelling: class shares with a dash (BRK.B -> BRK-B). */
const yahoo = (t: string) => t.trim().toUpperCase().replace(/^([A-Z]{1,5})[./]([A-Z])$/, "$1-$2");
const uniqSorted = (xs: string[]) => Array.from(new Set(xs)).sort();

const filersPath = arg("filers");
const spyPath = arg("spy-tickers");
const spyAsOf = arg("spy-as-of");
if (!filersPath || !spyPath || !spyAsOf || !/^\d{4}-\d{2}-\d{2}$/.test(spyAsOf)) {
  console.error("Usage: build-universes.ts --filers <universe json> --spy-tickers <txt> --spy-as-of YYYY-MM-DD");
  process.exit(1);
}

type Filers = { at: string; members: { ticker: string; medianDollarVolume20d: number }[] };
const filers = JSON.parse(fs.readFileSync(filersPath, "utf8")) as Filers;
const ranked = [...filers.members].sort((a, b) => b.medianDollarVolume20d - a.medianDollarVolume20d).map((m) => yahoo(m.ticker));
const filerTickers = ranked.filter((t) => PLAIN.test(t));

const graph = JSON.parse(fs.readFileSync(path.join(root, "..", "engine", "data", "graph.json"), "utf8")) as { generatedAt: string; names: Record<string, string> };
const graphTickers = Object.keys(graph.names).map(yahoo).filter((t) => PLAIN.test(t));

const spy = fs
  .readFileSync(spyPath, "utf8")
  .split(/\r?\n/)
  .map(yahoo)
  .filter((t) => PLAIN.test(t));

const lists = {
  falcon_universe: { asOf: filers.at.slice(0, 10), count: 0, tickers: uniqSorted(filerTickers) },
  falcon_graph: { asOf: graph.generatedAt.slice(0, 10), count: 0, tickers: uniqSorted(graphTickers) },
  us_large_caps: { asOf: filers.at.slice(0, 10), count: 0, tickers: uniqSorted(filerTickers.slice(0, 500)) },
  sp500_today: { asOf: spyAsOf, count: 0, tickers: uniqSorted(spy) },
};
for (const l of Object.values(lists)) l.count = l.tickers.length;

/** Wraps a space-separated list at about 120 characters. */
function wrap(tickers: string[]): string {
  const lines: string[] = [];
  let line = "";
  for (const t of tickers) {
    if (line.length + t.length + 1 > 116) {
      lines.push(line);
      line = "";
    }
    line += (line ? " " : "") + t;
  }
  if (line) lines.push(line);
  return lines.map((l) => `    "${l} "`).join(" +\n");
}

const body = `/**
 * Ticker lists behind Falcon's wide named universes (src/universes.ts).
 * Generated by scripts/build-universes.ts; do not edit by hand. Tickers and
 * as-of dates only. Each list is today's membership, so every backtest on it
 * over a past period carries the hindsight check (14).
 *
 * Pure; safe in the browser.
 */

export const UNIVERSE_LISTS = {
${Object.entries(lists)
  .map(([k, l]) => `  ${k}: {\n    asOf: "${l.asOf}",\n    count: ${l.count},\n    tickers:\n${wrap(l.tickers)},\n  },`)
  .join("\n")}
} as const;
`;
fs.writeFileSync(path.join(root, "src", "universe-lists.ts"), body);
