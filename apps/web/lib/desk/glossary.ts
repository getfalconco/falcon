type Extra = { ex?: [string, string]; at?: GlossaryPlace };

/** Compact entry builder: tr/en = [display term, ...more forms]. The display term is matched too unless it contains "(". */
function e(key: string, cls: GlossaryClass, tr: string[], en: string[], trDefs: string[], enDefs: string[], x: Extra = {}): GlossaryEntry {
  const side = (forms: string[], defs: string[], example?: string): GlossarySide => ({
    term: forms[0]!.replace(/^=/, ""),
    forms: forms[0]!.includes("(") ? forms.slice(1) : forms,
    defs,
    ...(example ? { example } : {}),
  });
  return { key, cls, tr: side(tr, trDefs, x.ex?.[0]), en: side(en, enDefs, x.ex?.[1]), ...(x.at ? { at: x.at } : {}) };
}

